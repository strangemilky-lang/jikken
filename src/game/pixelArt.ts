export function resolveWallThemeKey(paletteIdx: number, isSanctum: boolean): WallThemeKey {
  if (isSanctum) return 'sanctum';
  const keys: WallThemeKey[] = ['dungeon', 'golden', 'crimson', 'jade', 'void'];
  return keys[((paletteIdx % keys.length) + keys.length) % keys.length];
}

export function validateSpriteDefinition(def: PixelSpriteDef): boolean {
  if (def.width <= 0 || def.height <= 0) return false;
  for (const frame of def.frames) {
    if (frame.length !== def.height) return false;
    for (const row of frame) {
      if (row.length !== def.width) return false;
      for (const ch of row) {
        if (ch !== '.' && !(ch in def.palette)) return false;
      }
    }
  }
  return true;
}

const spriteCache = new Map<SpriteKey, CompiledSprite>();
const wallTexCache = new Map<string, HTMLCanvasElement>();

function createOffscreen(w: number, h: number): HTMLCanvasElement {
  const cv = document.createElement('canvas');
  cv.width = w;
  cv.height = h;
  return cv;
}

function buildSpriteFrameCanvas(
  def: PixelSpriteDef,
  rows: string[],
  flashWhite: boolean,
): HTMLCanvasElement {
  const cv = createOffscreen(def.width, def.height);
  const ctx = cv.getContext('2d');
  if (!ctx) return cv;
  for (let y = 0; y < def.height; y++) {
    const row = rows[y];
    for (let x = 0; x < def.width; x++) {
      const ch = row[x];
      if (ch === '.') continue;
      ctx.fillStyle = flashWhite ? '#ffffff' : def.palette[ch];
      ctx.fillRect(x, y, 1, 1);
    }
  }
  return cv;
}

export function getCompiledSprite(key: SpriteKey): CompiledSprite | null {
  if (typeof document === 'undefined') return null;
  const cached = spriteCache.get(key);
  if (cached) return cached;
  const def = SPRITE_REGISTRY[key];
  if (!def) return null;
  const compiled: CompiledSprite = {
    width: def.width,
    height: def.height,
    frames: [
      buildSpriteFrameCanvas(def, def.frames[0], false),
      buildSpriteFrameCanvas(def, def.frames[1], false),
    ],
    flashFrames: [
      buildSpriteFrameCanvas(def, def.frames[0], true),
      buildSpriteFrameCanvas(def, def.frames[1], true),
    ],
  };
  spriteCache.set(key, compiled);
  return compiled;
}

function clampByte(n: number): number {
  return Math.max(0, Math.min(255, Math.round(n)));
}

function rgbStr(r: number, g: number, b: number): string {
  return `rgb(${clampByte(r)},${clampByte(g)},${clampByte(b)})`;
}

export function getWallTextureCanvas(
  palette: FloorPalette,
  paletteIdx: number,
  isSanctum: boolean,
): HTMLCanvasElement | null {
  if (typeof document === 'undefined') return null;
  const theme = resolveWallThemeKey(paletteIdx, isSanctum);
  const cacheKey = `${theme}_${palette.wall.join(',')}`;
  const existing = wallTexCache.get(cacheKey);
  if (existing) return existing;

  const grid = WALL_TEXTURE_GRIDS[theme];
  const cv = createOffscreen(16, 16);
  const ctx = cv.getContext('2d');
  if (!ctx) return cv;

  const [wr, wg, wb] = isSanctum ? [88, 56, 138] : palette.wall;
  const colorMap: Record<string, string> = {
    '.': rgbStr(wr, wg, wb),
    l: rgbStr(wr * 1.18 + 12, wg * 1.18 + 12, wb * 1.18 + 12),
    d: rgbStr(wr * 0.52, wg * 0.52, wb * 0.52),
    a:
      theme === 'dungeon'
        ? rgbStr(wr * 0.72, wg * 1.08, wb * 0.72)
        : theme === 'golden'
          ? 'rgb(234, 179, 8)'
          : theme === 'crimson'
            ? 'rgb(239, 68, 68)'
            : theme === 'jade'
              ? 'rgb(45, 212, 191)'
              : theme === 'sanctum'
                ? 'rgb(168, 85, 247)'
                : 'rgb(192, 132, 252)',
    g:
      theme === 'golden'
        ? 'rgb(254, 240, 138)'
        : theme === 'crimson'
          ? 'rgb(253, 224, 71)'
          : theme === 'jade'
            ? 'rgb(165, 243, 252)'
            : theme === 'sanctum'
              ? 'rgb(244, 114, 182)'
              : 'rgb(224, 231, 255)',
  };

  for (let y = 0; y < 16; y++) {
    const row = grid[y];
    for (let x = 0; x < 16; x++) {
      const ch = row[x];
      ctx.fillStyle = colorMap[ch] ?? colorMap['.'];
      ctx.fillRect(x, y, 1, 1);
    }
  }

  wallTexCache.set(cacheKey, cv);
  return cv;
}
